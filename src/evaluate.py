"""
Regenerate every number in the README "Results" section.

    python -m src.evaluate                      # recompute, write results/metrics.json, update README
    python -m src.evaluate --check              # recompute and fail if it disagrees with the committed files
    python -m src.evaluate --protocol NAME      # recompute and print one protocol only

Protocols
---------
``group_shuffle``
    The protocol behind the README's "CV AUC 0.74": the exact preprocessing,
    GroupShuffleSplit folds and ensemble used by ``python -m src.model``.
    Clipping/scaling is fitted on all rows and folds are not time-ordered.

``walk_forward``
    Time-ordered evaluation. For each test year Y, train on quarters that ended
    more than ``EMBARGO_DAYS`` before 1 January of Y, test on quarters ending in
    Y. Clipping/scaling is fitted on the training rows only.

``*_no_yoy``
    The same protocols without ``eps_growth_yoy``, which is computed from the
    current quarter's reported EPS (the quantity the label is derived from).

``dataset``
    Size, date range and beat rate of ``data/earnings_dataset.csv``.
"""

import argparse
import json
import platform
import re
import sys
from pathlib import Path
from typing import Any, Callable, Dict, List, Optional, Tuple

import numpy as np
import pandas as pd
from sklearn.metrics import accuracy_score, f1_score, roc_auc_score

from src.data_loader import FEATURE_COLUMNS, TARGET_COLUMN, TRAINING_CSV, file_sha256
from src.model import (
    FeaturePreprocessor,
    fit_ensemble,
    group_shuffle_splits,
    predict_ensemble,
    prepare_feature_frame,
)
from src.utils import PROJECT_ROOT

RESULTS_JSON = PROJECT_ROOT / "results" / "metrics.json"
README = PROJECT_ROOT / "README.md"
README_START = "<!-- results:start (generated by `python -m src.evaluate`; do not edit by hand) -->"
README_END = "<!-- results:end -->"

LEAKY_FEATURE = "eps_growth_yoy"
FEATURES_NO_YOY = [f for f in FEATURE_COLUMNS if f != LEAKY_FEATURE]
HEURISTIC_FEATURE = "eps_consistency"  # rolling 4-quarter beat rate, used as a raw score

FIRST_TEST_YEAR = 2010
EMBARGO_DAYS = 90  # gap so every training label was announced before any test quarter

# --check tolerance for model metrics (tree libraries can differ slightly by CPU/threads)
METRIC_TOLERANCE = 0.002
DECIMALS = 4

Split = Tuple[np.ndarray, np.ndarray]


# ═══════════════════════════════════════════════════════════════════════════════
# DATA + SPLITS
# ═══════════════════════════════════════════════════════════════════════════════
def load_dataset(path: Path = TRAINING_CSV) -> pd.DataFrame:
    """Load the committed training CSV with ``quarter_end`` parsed as dates."""
    df = pd.read_csv(path)
    df["quarter_end"] = pd.to_datetime(df["quarter_end"])
    return df.reset_index(drop=True)


def walk_forward_splits(
    dates: pd.Series,
    first_test_year: int = FIRST_TEST_YEAR,
    embargo_days: int = EMBARGO_DAYS,
) -> List[Tuple[int, np.ndarray, np.ndarray]]:
    """Expanding-window yearly splits where training always precedes testing.

    Returns ``(test_year, train_idx, test_idx)`` triples of positional indices.
    Training rows end more than ``embargo_days`` before 1 January of the test
    year; test rows are the quarters ending in that year.
    """
    dates = pd.to_datetime(pd.Series(dates)).reset_index(drop=True)
    years = sorted(int(y) for y in dates.dt.year.unique() if y >= first_test_year)
    splits = []
    for year in years:
        cutoff = pd.Timestamp(year=year, month=1, day=1) - pd.Timedelta(days=embargo_days)
        train_idx = np.flatnonzero((dates < cutoff).to_numpy())
        test_idx = np.flatnonzero((dates.dt.year == year).to_numpy())
        if len(train_idx) and len(test_idx):
            splits.append((year, train_idx, test_idx))
    return splits


def fit_predict(
    train_df: pd.DataFrame, test_df: pd.DataFrame, features: List[str],
) -> np.ndarray:
    """Fit preprocessing + ensemble on ``train_df`` only and score ``test_df``."""
    X_train = prepare_feature_frame(train_df, features)
    X_test = prepare_feature_frame(test_df, features)
    pre = FeaturePreprocessor().fit(X_train)
    xgb_model, lgbm_model = fit_ensemble(pre.transform(X_train), train_df[TARGET_COLUMN])
    return predict_ensemble(xgb_model, lgbm_model, pre.transform(X_test))


# ═══════════════════════════════════════════════════════════════════════════════
# PROTOCOLS
# ═══════════════════════════════════════════════════════════════════════════════
def _r(x: float) -> float:
    return round(float(x), DECIMALS)


def dataset_summary(df: pd.DataFrame, csv_path: Path = TRAINING_CSV) -> Dict[str, Any]:
    return {
        "rows": int(len(df)),
        "tickers": int(df["ticker"].nunique()),
        "first_quarter_end": df["quarter_end"].min().strftime("%Y-%m-%d"),
        "last_quarter_end": df["quarter_end"].max().strftime("%Y-%m-%d"),
        "beat_rate": _r(df[TARGET_COLUMN].mean()),
        "csv_sha256": file_sha256(csv_path),
    }


def group_shuffle(df: pd.DataFrame, features: List[str]) -> Dict[str, Any]:
    """Replicates the CV loop in ``src.model.train_models`` as run by ``main``."""
    X = prepare_feature_frame(df, features)
    X = FeaturePreprocessor().fit(X).transform(X)  # fitted on all rows, as in src.model.main
    y = df[TARGET_COLUMN]
    groups = df["ticker"]

    aucs, accs, f1s, majority, heuristic, held_out = [], [], [], [], [], set()
    for train_idx, val_idx in group_shuffle_splits(X, y, groups):
        y_tr, y_val = y.iloc[train_idx], y.iloc[val_idx]
        xgb_model, lgbm_model = fit_ensemble(X.iloc[train_idx], y_tr, X.iloc[val_idx], y_val)
        proba = predict_ensemble(xgb_model, lgbm_model, X.iloc[val_idx])
        preds = (proba >= 0.5).astype(int)
        aucs.append(roc_auc_score(y_val, proba))
        accs.append(accuracy_score(y_val, preds))
        f1s.append(f1_score(y_val, preds, average="weighted", zero_division=0))
        train_majority = int(y_tr.mean() >= 0.5)
        majority.append(float((y_val == train_majority).mean()))
        heuristic.append(roc_auc_score(y_val, df[HEURISTIC_FEATURE].iloc[val_idx]))
        held_out.update(groups.iloc[val_idx].unique())

    return {
        "folds": len(aucs),
        "auc": _r(np.mean(aucs)),
        "accuracy": _r(np.mean(accs)),
        "f1_weighted": _r(np.mean(f1s)),
        "majority_class_accuracy": _r(np.mean(majority)),
        "eps_consistency_auc": _r(np.mean(heuristic)),
        "distinct_tickers_held_out": len(held_out),
    }


def walk_forward(df: pd.DataFrame, features: List[str]) -> Dict[str, Any]:
    y = df[TARGET_COLUMN]
    splits = walk_forward_splits(df["quarter_end"])
    proba = np.full(len(df), np.nan)
    majority_pred = np.full(len(df), -1)
    for _, train_idx, test_idx in splits:
        proba[test_idx] = fit_predict(df.iloc[train_idx], df.iloc[test_idx], features)
        majority_pred[test_idx] = int(y.iloc[train_idx].mean() >= 0.5)

    tested = ~np.isnan(proba)
    y_t, p_t = y[tested], proba[tested]
    return {
        "first_test_year": splits[0][0],
        "last_test_year": splits[-1][0],
        "test_rows": int(tested.sum()),
        "auc": _r(roc_auc_score(y_t, p_t)),
        "accuracy": _r(accuracy_score(y_t, (p_t >= 0.5).astype(int))),
        "majority_class_accuracy": _r((y_t == majority_pred[tested]).mean()),
        "eps_consistency_auc": _r(roc_auc_score(y_t, df[HEURISTIC_FEATURE][tested])),
    }


PROTOCOLS: Dict[str, Callable[[pd.DataFrame], Dict[str, Any]]] = {
    "dataset": dataset_summary,
    "group_shuffle": lambda df: group_shuffle(df, FEATURE_COLUMNS),
    "group_shuffle_no_yoy": lambda df: group_shuffle(df, FEATURES_NO_YOY),
    "walk_forward": lambda df: walk_forward(df, FEATURE_COLUMNS),
    "walk_forward_no_yoy": lambda df: walk_forward(df, FEATURES_NO_YOY),
}


def compute_results(df: Optional[pd.DataFrame] = None) -> Dict[str, Any]:
    df = load_dataset() if df is None else df
    return {name: fn(df) for name, fn in PROTOCOLS.items()}


def environment() -> Dict[str, str]:
    import lightgbm
    import sklearn
    import xgboost
    return {
        "python": platform.python_version(),
        "pandas": pd.__version__,
        "numpy": np.__version__,
        "scikit-learn": sklearn.__version__,
        "xgboost": xgboost.__version__,
        "lightgbm": lightgbm.__version__,
    }


# ═══════════════════════════════════════════════════════════════════════════════
# README RENDERING
# ═══════════════════════════════════════════════════════════════════════════════
def _cmd(protocol: str) -> str:
    return f"`python -m src.evaluate --protocol {protocol}`"


def render_results_section(results: Dict[str, Any]) -> str:
    """Markdown for the README block. Every value comes from ``results``."""
    d, g, g2 = results["dataset"], results["group_shuffle"], results["group_shuffle_no_yoy"]
    w, w2 = results["walk_forward"], results["walk_forward_no_yoy"]
    f3 = lambda x: f"{x:.3f}"  # noqa: E731
    rows = [
        ("**Dataset** (`data/earnings_dataset.csv`)", "", ""),
        ("Rows", f"{d['rows']:,}", _cmd("dataset")),
        ("Tickers", str(d["tickers"]), _cmd("dataset")),
        ("Quarter-end range", f"{d['first_quarter_end']} to {d['last_quarter_end']}", _cmd("dataset")),
        ("Beat rate (share of rows with label 1)", f3(d["beat_rate"]), _cmd("dataset")),
        ("SHA-256 of the CSV; rebuilding it from `data/cache/` must give the same hash",
         f"`{d['csv_sha256'][:16]}…`", "`python -m src.data_loader --rebuild-from-cache --check`"),
        (f"**Ticker-holdout CV**: the protocol behind the README's 0.74 "
         f"(GroupShuffleSplit, {g['folds']} folds, not time-ordered)", "", ""),
        ("Mean fold ROC-AUC", f3(g["auc"]), _cmd("group_shuffle")),
        ("Mean fold accuracy", f3(g["accuracy"]), _cmd("group_shuffle")),
        ("Mean fold F1 (weighted)", f3(g["f1_weighted"]), _cmd("group_shuffle")),
        ("Mean fold majority-class accuracy", f3(g["majority_class_accuracy"]), _cmd("group_shuffle")),
        (f"Mean fold ROC-AUC of `{HEURISTIC_FEATURE}` alone (no model)",
         f3(g["eps_consistency_auc"]), _cmd("group_shuffle")),
        ("Distinct tickers held out across all folds",
         f"{g['distinct_tickers_held_out']} of {d['tickers']}", _cmd("group_shuffle")),
        (f"Mean fold ROC-AUC without `{LEAKY_FEATURE}`", f3(g2["auc"]), _cmd("group_shuffle_no_yoy")),
        (f"**Walk-forward**: train on quarters ending > {EMBARGO_DAYS} days before 1 Jan of year Y, "
         f"test on year Y, Y = {w['first_test_year']}–{w['last_test_year']}", "", ""),
        ("Pooled ROC-AUC", f3(w["auc"]), _cmd("walk_forward")),
        ("Accuracy", f3(w["accuracy"]), _cmd("walk_forward")),
        ("Majority-class accuracy", f3(w["majority_class_accuracy"]), _cmd("walk_forward")),
        (f"ROC-AUC of `{HEURISTIC_FEATURE}` alone (no model)", f3(w["eps_consistency_auc"]), _cmd("walk_forward")),
        ("Test rows", f"{w['test_rows']:,}", _cmd("walk_forward")),
        (f"Pooled ROC-AUC without `{LEAKY_FEATURE}`", f3(w2["auc"]), _cmd("walk_forward_no_yoy")),
        (f"Accuracy without `{LEAKY_FEATURE}`", f3(w2["accuracy"]), _cmd("walk_forward_no_yoy")),
    ]
    lines = [
        README_START,
        "",
        "Every number below is regenerated from the committed data by the command next to it "
        "(`make reproduce` runs them all and fails if any drifts from `results/metrics.json`).",
        "",
        "| Number | Value | Command |",
        "|---|---|---|",
    ]
    lines += [f"| {a} | {b} | {c} |" for a, b, c in rows]
    lines += [
        "",
        f"`{LEAKY_FEATURE}` compares the current quarter's *reported* EPS with the same quarter a year "
        "earlier, so it is not known before the announcement it is used to predict. The "
        f"`without {LEAKY_FEATURE}` rows show the protocols with that feature removed.",
        "",
        README_END,
    ]
    return "\n".join(lines)


def update_readme(results: Dict[str, Any], readme: Path = README) -> None:
    text = readme.read_text(encoding="utf-8")
    block = render_results_section(results)
    pattern = re.compile(re.escape(README_START) + r".*?" + re.escape(README_END), re.S)
    if not pattern.search(text):
        raise RuntimeError(f"{readme} has no results markers")
    readme.write_text(pattern.sub(lambda _: block, text), encoding="utf-8")


def readme_results_block(readme: Path = README) -> Optional[str]:
    text = readme.read_text(encoding="utf-8")
    m = re.search(re.escape(README_START) + r".*?" + re.escape(README_END), text, re.S)
    return m.group(0) if m else None


# ═══════════════════════════════════════════════════════════════════════════════
# CHECK
# ═══════════════════════════════════════════════════════════════════════════════
def compare(expected: Any, actual: Any, path: str = "") -> List[str]:
    """List the differences between committed and regenerated results."""
    if isinstance(expected, dict) and isinstance(actual, dict):
        problems = []
        for key in sorted(set(expected) | set(actual)):
            if key not in expected or key not in actual:
                problems.append(f"{path}{key}: present in only one of committed/regenerated")
            else:
                problems += compare(expected[key], actual[key], f"{path}{key}.")
        return problems
    if isinstance(expected, float) or isinstance(actual, float):
        if abs(float(expected) - float(actual)) > METRIC_TOLERANCE:
            return [f"{path[:-1]}: committed {expected} vs regenerated {actual}"]
        return []
    return [] if expected == actual else [f"{path[:-1]}: committed {expected!r} vs regenerated {actual!r}"]


def main(argv: Optional[List[str]] = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--protocol", choices=sorted(PROTOCOLS), help="Compute and print one protocol only.")
    parser.add_argument("--check", action="store_true",
                        help="Fail if regenerated numbers differ from results/metrics.json "
                             "or the README block is out of date.")
    args = parser.parse_args(argv)

    if args.protocol:
        print(json.dumps({args.protocol: PROTOCOLS[args.protocol](load_dataset())}, indent=2))
        return 0

    results = compute_results()

    if args.check:
        committed = json.loads(RESULTS_JSON.read_text())
        committed.pop("environment", None)
        problems = compare(committed, results)
        if readme_results_block() != render_results_section(committed):
            problems.append("README results block does not match results/metrics.json "
                            "(run `python -m src.evaluate`)")
        print(json.dumps(results, indent=2))
        if problems:
            print("\nMISMATCH:\n  " + "\n  ".join(problems))
            return 1
        print(f"\nOK: regenerated results match {RESULTS_JSON.relative_to(PROJECT_ROOT)} "
              f"(tolerance {METRIC_TOLERANCE}) and the README block")
        return 0

    RESULTS_JSON.parent.mkdir(parents=True, exist_ok=True)
    RESULTS_JSON.write_text(json.dumps({**results, "environment": environment()}, indent=2) + "\n")
    update_readme(results)
    print(json.dumps(results, indent=2))
    print(f"\nWrote {RESULTS_JSON.relative_to(PROJECT_ROOT)} and updated the README results block")
    return 0


if __name__ == "__main__":
    sys.exit(main())
